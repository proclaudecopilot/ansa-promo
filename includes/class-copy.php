	public static function placeholders( $text ) {
		preg_match_all( '/\{\{\s*([a-z0-9_]+)\s*\}\}/i', (string) $text, $m );
		return array_values( array_unique( $m[1] ) );
	}

	/** Непознати плейсхолдъри + небалансирани скоби за даден текст → списък с грешки (празен = ОК). */
	public static function validate( $text ) {
		$errs = array();
		$t = (string) $text;
		if ( substr_count( $t, '{{' ) !== substr_count( $t, '}}' ) ) { $errs[] = 'небалансирани {{ }}'; }
		foreach ( self::placeholders( $t ) as $v ) { if ( ! in_array( $v, self::vars(), true ) ) { $errs[] = 'непознат плейсхолдър {{' . $v . '}}'; } }
		return $errs;
	}

	public static function render( $template, $vars ) {
		return preg_replace_callback( '/\{\{\s*([a-z0-9_]+)\s*\}\}/i', function ( $m ) use ( $vars ) {
			return array_key_exists( $m[1], $vars ) ? (string) $vars[ $m[1] ] : $m[0];
		}, (string) $template );
	}
}
