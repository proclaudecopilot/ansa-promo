	public static function defaults() {
		$out = array();
		foreach ( self::registry() as $g ) { foreach ( $g as $k => $v ) { $out[ $k ] = $v; } }
		return $out;
	}

	/** key → група. */
	public static function group_of( $key ) {
		foreach ( self::registry() as $g => $keys ) { if ( isset( $keys[ $key ] ) ) return $g; }
		return '';
	}

	/** v1.19.0: при включени седмици дефолтните текстове, които говорят за една фиксирана отстъпка, се заместват с week-aware вариантите
	 *  (ключ.weekly) — само ако админът не е редактирал оригиналния ключ. */
	public static function weekly( $copy, $overrides ) {
		foreach ( array( 'how.hero.note', 'how.faq.8.a' ) as $k ) { if ( isset( $copy[ $k . '.weekly' ] ) && ( ! is_array( $overrides ) || ! isset( $overrides[ $k ] ) ) ) { $copy[ $k ] = $copy[ $k . '.weekly' ]; } }
		return $copy;
	}
	/** Дефолтите + само реално различните override-и. */
	public static function effective( $overrides ) {
		$d = self::defaults();
		if ( is_array( $overrides ) ) {
			foreach ( $overrides as $k => $v ) {
				if ( isset( $d[ $k ] ) && is_string( $v ) && $v !== $d[ $k ] ) { $d[ $k ] = $v; }
			}
		}
		return $d;
	}

