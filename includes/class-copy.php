	public static function defaults() {
		$out = array();
		foreach ( self::registry() as $g ) { foreach ( $g as $k => $v ) { $out[ $k ] = $v; } }
		return $out;
	}

	/** key → група. */
	public static function group_of( $key ) {
		foreach ( self::registry() as $g => $keys ) { if ( isset( $keys[ $key ] ) ) return $g; }
		return '';
	}

	/** Дефолтите + само реално различните override-и. */
	public static function effective( $overrides ) {
		$d = self::defaults();
		if ( is_array( $overrides ) ) {
			foreach ( $overrides as $k => $v ) {
				if ( isset( $d[ $k ] ) && is_string( $v ) && $v !== $d[ $k ] ) { $d[ $k ] = $v; }
			}
		}
		return $d;
	}

	/** Само променените (за запис). */
	public static function diff( $copy ) {
		$d = self::defaults(); $out = array();
		if ( ! is_array( $copy ) ) { return $out; }
		foreach ( $copy as $k => $v ) {
			if ( isset( $d[ $k ] ) && is_string( $v ) && trim( $v ) !== '' && $v !== $d[ $k ] ) { $out[ $k ] = $v; }
		}
		return $out;
	}

	/** Плейсхолдърите в един текст. */
	public static function placeholders( $text ) {
		preg_match_all( '/\{\{\s*([a-z0-9_]+)\s*\}\}/i', (string) $text, $m );
		return array_values( array_unique( $m[1] ) );
	}

	/** Непознати плейсхолдъри + небалансирани скоби за даден текст → списък с грешки (празен = ОК). */
	public static function validate( $text ) {
		$errs = array();
		$t = (string) $text;
		if ( substr_count( $t, '{{' ) !== substr_count( $t, '}}' ) ) { $errs[] = 'небалансирани {{ }}'; }
		foreach ( self::placeholders( $t ) as $v ) { if ( ! in_array( $v, self::vars(), true ) ) { $errs[] = 'непознат плейсхолдър {{' . $v . '}}'; } }
		return $errs;
	}

	public static function render( $template, $vars ) {
		return preg_replace_callback( '/\{\{\s*([a-z0-9_]+)\s*\}\}/i', function ( $m ) use ( $vars ) {
			return array_key_exists( $m[1], $vars ) ? (string) $vars[ $m[1] ] : $m[0];
		}, (string) $template );
	}
